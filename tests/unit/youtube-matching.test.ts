import { describe, it, expect, vi, beforeEach } from "vitest";
import {
  parseYouTubeDuration,
  extractIsrcFromYouTubeDescription,
  cleanYouTubeChannelTitle,
  stripYouTubeVideoNoise,
  parseYouTubeVideoTitle,
} from "@/modules/matching/youtube-normalizer";
import {
  searchYouTubeCatalog,
  retrieveAndMatchCandidates,
} from "@/modules/matching/matching-engine";
import { ProviderType, TrackMatchReviewStatus } from "@prisma/client";

// Set environment before tests
process.env.AUTH_SECRET = "test-secret-at-least-32-chars-long-123456";
process.env.DATABASE_URL = "postgresql://postgres:postgres@localhost:5432/sonora_dev";
process.env.TOKEN_ENCRYPTION_KEY = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
process.env.REDIS_URL = "redis://localhost:6379";

describe("YouTube Metadata Normalization & Catalog Matching (P5-T03)", () => {
  beforeEach(() => {
    vi.restoreAllMocks();
  });

  describe("ISO 8601 Duration Parsing", () => {
    it("parses minute and second formats accurately", () => {
      expect(parseYouTubeDuration("PT3M45S")).toBe(225000); // 3*60 + 45 = 225s
      expect(parseYouTubeDuration("PT45S")).toBe(45000);
      expect(parseYouTubeDuration("PT2M")).toBe(120000);
    });

    it("parses hours, minutes, and seconds accurately", () => {
      expect(parseYouTubeDuration("PT1H2M3S")).toBe(3723000); // 3600 + 120 + 3 = 3723s
    });

    it("handles zero, missing, or malformed inputs safely", () => {
      expect(parseYouTubeDuration("")).toBe(0);
      expect(parseYouTubeDuration("P0D")).toBe(0);
      expect(parseYouTubeDuration("PT0S")).toBe(0);
      expect(parseYouTubeDuration("invalid-duration")).toBe(0);
    });
  });

  describe("ISRC Extraction from Descriptions", () => {
    it("extracts labeled ISRC with whitespace or colon", () => {
      const desc = `
        Provided to YouTube by Warner Records
        Levitating · Dua Lipa
        ℗ 2020 Warner Records UK
        ISRC: GBAHT1901299
        Auto-generated by YouTube.
      `;
      expect(extractIsrcFromYouTubeDescription(desc)).toBe("GBAHT1901299");
    });

    it("extracts lowercase or hyphenated ISRC", () => {
      const desc = "Master track details: isrc: US-UM7-19-00123\nRecord Label: Interscope";
      expect(extractIsrcFromYouTubeDescription(desc)).toBe("USUM71900123");
    });

    it("returns null when no valid ISRC exists", () => {
      expect(extractIsrcFromYouTubeDescription("Just a video description with no codes")).toBeNull();
      expect(extractIsrcFromYouTubeDescription("")).toBeNull();
    });
  });

  describe("Channel Title Cleaning", () => {
    it("strips - Topic suffix cleanly", () => {
      expect(cleanYouTubeChannelTitle("Dua Lipa - Topic")).toBe("Dua Lipa");
      expect(cleanYouTubeChannelTitle("The Weeknd - Topic")).toBe("The Weeknd");
    });

    it("strips VEVO and Official qualifiers", () => {
      expect(cleanYouTubeChannelTitle("TaylorSwiftVEVO")).toBe("TaylorSwift");
      expect(cleanYouTubeChannelTitle("Adele Official Channel")).toBe("Adele");
    });
  });

  describe("Video Noise Stripping", () => {
    it("strips resolution and quality tags", () => {
      expect(stripYouTubeVideoNoise("Levitating [Official 4K Video]")).toBe("Levitating");
      expect(stripYouTubeVideoNoise("Blinding Lights (HD) 1080p")).toBe("Blinding Lights");
      expect(stripYouTubeVideoNoise("Song Title [4K UHD]")).toBe("Song Title");
    });

    it("strips video and audio tags", () => {
      expect(stripYouTubeVideoNoise("Song Name (Official Music Video)")).toBe("Song Name");
      expect(stripYouTubeVideoNoise("Song Name [Official Audio]")).toBe("Song Name");
      expect(stripYouTubeVideoNoise("Song Name (Visualizer)")).toBe("Song Name");
      expect(stripYouTubeVideoNoise("Song Name (Lyric Video)")).toBe("Song Name");
      expect(stripYouTubeVideoNoise("Song Name - Official Video")).toBe("Song Name");
    });
  });

  describe("YouTube Title Parsing & Version Classification", () => {
    it("disentangles Artist - Title format and identifies official music video", () => {
      const parsed = parseYouTubeVideoTitle(
        "Dua Lipa - Levitating (Official Music Video)",
        "Dua Lipa"
      );
      expect(parsed.artist).toBe("Dua Lipa");
      expect(parsed.title).toBe("Levitating");
      expect(parsed.cleanTitle).toBe("Levitating");
      expect(parsed.recordingType).toBe("ORIGINAL");
      expect(parsed.isMusicVideo).toBe(true);
    });

    it("correctly identifies Live versions and prevents conflation with original", () => {
      const parsed = parseYouTubeVideoTitle(
        "Queen - Bohemian Rhapsody (Live at Wembley 1986)",
        "Queen"
      );
      expect(parsed.artist).toBe("Queen");
      expect(parsed.cleanTitle).toBe("Bohemian Rhapsody");
      expect(parsed.recordingType).toBe("LIVE");
      expect(parsed.isLive).toBe(true);
    });

    it("identifies Remix versions", () => {
      const parsed = parseYouTubeVideoTitle(
        "Dua Lipa - Levitating (feat. DaBaby) [Don Diablo Remix]",
        "Dua Lipa"
      );
      expect(parsed.recordingType).toBe("REMIX");
      expect(parsed.isRemix).toBe(true);
    });

    it("identifies Cover versions", () => {
      const parsed = parseYouTubeVideoTitle(
        "Someone - Levitating (Acoustic Cover)",
        "Someone"
      );
      expect(parsed.recordingType).toBe("COVER");
      expect(parsed.isCover).toBe(true);
    });
  });

  describe("searchYouTubeCatalog & Quota Isolation", () => {
    it("calls search.list and videos.list with correct query and returns candidate tracks", async () => {
      const mockFetch = vi.fn();
      global.fetch = mockFetch;

      // 1. search.list response
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: { videoId: "vid123" },
              snippet: {
                title: "Dua Lipa - Levitating (Official Audio)",
                channelTitle: "Dua Lipa - Topic",
                description: "ISRC: GBAHT1901299\nProvided to YouTube by Warner Records",
              },
            },
          ],
        }),
      });

      // 2. videos.list response
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: "vid123",
              snippet: {
                title: "Dua Lipa - Levitating (Official Audio)",
                channelTitle: "Dua Lipa - Topic",
                description: "ISRC: GBAHT1901299\nProvided to YouTube by Warner Records",
              },
              contentDetails: {
                duration: "PT3M23S",
              },
            },
          ],
        }),
      });

      const candidates = await searchYouTubeCatalog("Levitating Dua Lipa", {
        accessToken: "mock-token",
        userId: "user-test-search",
        useCache: false,
      });

      expect(candidates).toHaveLength(1);
      expect(candidates[0].id).toBe("vid123");
      expect(candidates[0].provider).toBe(ProviderType.YOUTUBE_MUSIC);
      expect(candidates[0].title).toBe("Levitating");
      expect(candidates[0].artistName).toBe("Dua Lipa");
      expect(candidates[0].durationMs).toBe(203000);
      expect(candidates[0].isrc).toBe("GBAHT1901299");
      expect(candidates[0].uri).toBe("https://www.youtube.com/watch?v=vid123");
    });
  });

  describe("retrieveAndMatchCandidates Tiered Gating", () => {
    it("matches canonical track to YouTube video with Tier 1 exact ISRC", async () => {
      const mockFetch = vi.fn();
      global.fetch = mockFetch;

      // search.list
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: { videoId: "yt-isrc-match" },
              snippet: {
                title: "Dua Lipa - Levitating",
                channelTitle: "Dua Lipa - Topic",
                description: "ISRC: GBAHT1901299",
              },
            },
          ],
        }),
      });

      // videos.list
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: "yt-isrc-match",
              snippet: {
                title: "Dua Lipa - Levitating",
                channelTitle: "Dua Lipa - Topic",
                description: "ISRC: GBAHT1901299",
              },
              contentDetails: {
                duration: "PT3M23S", // 203000 ms
              },
            },
          ],
        }),
      });

      const source = {
        title: "Levitating",
        artistName: "Dua Lipa",
        durationMs: 203000,
        isrc: "GBAHT1901299",
      };

      const result = await retrieveAndMatchCandidates(
        source,
        ProviderType.YOUTUBE_MUSIC,
        {
          youTubeAccessToken: "mock-token",
          userId: "user-matching-test",
        }
      );

      expect(result.bestMatch).not.toBeNull();
      expect(result.bestMatch?.id).toBe("yt-isrc-match");
      expect(result.reviewStatus).toBe(TrackMatchReviewStatus.AUTO_MATCHED);
      expect(result.isConflict).toBe(false);
    });

    it("flags conflict when source is studio ORIGINAL but YouTube candidate is LIVE", async () => {
      const mockFetch = vi.fn();
      global.fetch = mockFetch;

      // search.list
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: { videoId: "yt-live-candidate" },
              snippet: {
                title: "Queen - Bohemian Rhapsody (Live at Wembley)",
                channelTitle: "Queen",
                description: "Live concert footage",
              },
            },
          ],
        }),
      });

      // videos.list
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: "yt-live-candidate",
              snippet: {
                title: "Queen - Bohemian Rhapsody (Live at Wembley)",
                channelTitle: "Queen",
                description: "Live concert footage",
              },
              contentDetails: {
                duration: "PT5M55S",
              },
            },
          ],
        }),
      });

      const studioSource = {
        title: "Bohemian Rhapsody",
        artistName: "Queen",
        durationMs: 354000, // Studio length ~5m54s
      };

      const result = await retrieveAndMatchCandidates(
        studioSource,
        ProviderType.YOUTUBE_MUSIC,
        {
          youTubeAccessToken: "mock-token",
          userId: "user-matching-live-test",
        }
      );

      expect(result.bestMatch).not.toBeNull();
      // Version incompatibility must trigger NEEDS_REVIEW and isConflict
      expect(result.isConflict).toBe(true);
      expect(result.reviewStatus).toBe(TrackMatchReviewStatus.NEEDS_REVIEW);
      expect(result.conflictReason).toMatch(/Incompatible version|Version conflict/i);
    });

    it("flags review when duration delta exceeds 10s tolerance threshold", async () => {
      const mockFetch = vi.fn();
      global.fetch = mockFetch;

      // search.list returns video with dialogue intro that is 25s longer
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: { videoId: "yt-long-video" },
              snippet: {
                title: "Adele - Hello (Official Music Video)",
                channelTitle: "Adele",
                description: "Official music video with intro dialogue",
              },
            },
          ],
        }),
      });

      // videos.list
      mockFetch.mockResolvedValueOnce({
        ok: true,
        json: async () => ({
          items: [
            {
              id: "yt-long-video",
              snippet: {
                title: "Adele - Hello (Official Music Video)",
                channelTitle: "Adele",
                description: "Official music video with intro dialogue",
              },
              contentDetails: {
                duration: "PT5M20S", // 320,000 ms
              },
            },
          ],
        }),
      });

      const studioSource = {
        title: "Hello",
        artistName: "Adele",
        durationMs: 295000, // 4m55s (25s delta from 5m20s video)
      };

      const result = await retrieveAndMatchCandidates(
        studioSource,
        ProviderType.YOUTUBE_MUSIC,
        {
          youTubeAccessToken: "mock-token",
          userId: "user-matching-duration-test",
        }
      );

      expect(result.bestMatch).not.toBeNull();
      // Delta > 10s without ISRC should be gated for review
      expect(result.reviewStatus).toBe(TrackMatchReviewStatus.NEEDS_REVIEW);
      expect(result.conflictReason).toMatch(/duration/i);
    });
  });
});
